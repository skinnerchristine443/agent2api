function keyFor<T extends Record<string, string>>(map: T, code: string): T[keyof T] | undefined {
  return Object.prototype.hasOwnProperty.call(map, code) ? map[code as keyof T] : undefined
}

/** 将运行时 code 解析为其 i18n key，未知时返回 `undefined`。 */
export function updateStateKey(code: string) { return keyFor(UPDATE_STATE_KEYS, code) }
export function reasoningLevelKey(code: string) { return keyFor(REASONING_LEVEL_KEYS, code) }
export function logsRoutingKey(code: string) { return keyFor(LOGS_ROUTING_KEYS, code) }

/**
 * 传递给各组件的翻译辅助函数签名。key 是
 * 字面量 key 联合类型，因此未知 key 会编译报错，
 * 而不是把 key 原样渲染到屏幕上。
 */
export type Translate = (key: DictKey, vars?: Record<string, string | number>) => string

export function translate(key: DictKey, vars: Record<string, string | number> = {}) {
  const value: unknown = messages.zh[key]
  if (typeof value !== 'string') return key
  return value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`))
}
